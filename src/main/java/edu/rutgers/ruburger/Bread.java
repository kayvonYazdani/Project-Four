package edu.rutgers.ruburger;

/**
 * Represents the available bread options at RU Burger.
 * Sandwiches can use all five bread types, while burgers
 * are limited to brioche, wheat, and pretzel.
 *
 * @author Kayvon Yazdani
 */
public enum Bread {
    BRIOCHE,
    WHEAT,
    PRETZEL,
    BAGEL,
    SOURDOUGH
}
